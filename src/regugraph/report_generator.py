"""Executive Compliance Report and Legal Redline Generator for ReguGraph-UAE."""
from datetime import datetime
from typing import Dict, Any, List
from .graph_state import AuditState


def generate_markdown_report(state: AuditState) -> str:
    """Generate a formal regulatory audit dossier formatted in GitHub Flavored Markdown."""
    title = state.get("contract_title", "Evaluated Credit Contract")
    date_str = datetime.now().strftime("%d %B %Y, %H:%M GST")
    status = state.get("overall_status", "UNKNOWN")
    summary = state.get("executive_summary", "")
    findings = state.get("compliance_findings", [])
    actions = state.get("action_plan", [])
    clauses = state.get("extracted_clauses", [])
    math_val = state.get("math_validations", {})

    status_badge = "🟢 FULLY COMPLIANT" if status == "FULLY_COMPLIANT" else ("🔴 STATUTORY VIOLATIONS DETECTED" if status == "NON_COMPLIANT_INFRACTIONS_DETECTED" else "🟡 INQUIRY REFUSED / OUT OF SCOPE")

    violations = [f for f in findings if f["status"] == "VIOLATION"]
    total_refund = sum(f.get("excess_financial_impact_aed", 0.0) for f in violations)

    report = f"""# CBUAE Regulatory Compliance Audit Dossier
**Audited Facility:** {title}  
**Date of Audit:** {date_str}  
**Regulatory Standard:** Central Bank of the UAE (Consumer Protection Regulation & Standards)  
**Overall Status:** {status_badge}  

---

## 1. Executive Summary
{summary}

"""

    if violations:
        report += f"""
### ⚠️ Financial Restitution Summary
* **Total Unlawful Overcharges Detected:** **AED {total_refund:,.2f}**
* **Statutory Refund Due to Borrower:** **AED {total_refund:,.2f}**
* **Statutory Violations Count:** **{len(violations)} Non-Compliant Clauses**

---
"""

    report += """## 2. Key Contractual Parameters Extracted
| Contract Parameter | Extracted Term |
| :--- | :--- |
"""
    for c in clauses:
        report += f"| **{c['clause_type']}** | {c['contract_statement']} |\n"

    report += """
---

## 3. Detailed Regulatory Findings & Citations
"""
    for idx, f in enumerate(findings, 1):
        icon = "🔴" if f["status"] == "VIOLATION" else "🟢"
        report += f"""
### {icon} Finding {idx}: {f['checkpoint_name']} — `{f['status']}`
* **Contract Provision:** *"{f['contract_provision']}"*
* **Governing Rule:** {f['statutory_rule']}
* **Official Legal Citation:** `{f['legal_citation']}`
* **Legal Assessment:** {f['explanation']}
"""
        if f["status"] == "VIOLATION":
            report += f"* **Financial Impact:** Excess charge of **AED {f['excess_financial_impact_aed']:,.2f}**\n"
            report += f"* **Required Remediation:** {f['required_remediation']}\n"

    report += """
---

## 4. Mandatory Remediation & Action Plan
"""
    for idx, act in enumerate(actions, 1):
        report += f"{idx}. {act}\n"

    report += """
---
*Confidential — Generated by ReguGraph-UAE Autonomous Compliance Intelligence Engine.*
"""
    return report


generate_markdown_dossier = generate_markdown_report
